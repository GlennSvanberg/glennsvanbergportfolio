import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { renderDefaultOgPng } from '../src/lib/renderOgPng.ts'

const appDir = dirname(fileURLToPath(import.meta.url))
const root = join(appDir, '..')
const blackPath = join(root, 'assets/og/Inter-Black.ttf')
const regularPath = join(root, 'assets/og/Inter-Regular.ttf')
const black = readFileSync(blackPath).toString('base64')
const regular = readFileSync(regularPath).toString('base64')

const generated = `// Generated by scripts/generate-og.ts from assets/og.
// Inter is licensed under the SIL Open Font License (assets/og/LICENSE.txt).
export const interBlackBase64 = ${JSON.stringify(black)}
export const interRegularBase64 = ${JSON.stringify(regular)}
`

writeFileSync(join(root, 'src/lib/ogFonts.generated.ts'), generated)
writeFileSync(
  join(root, 'public/og.png'),
  renderDefaultOgPng([blackPath, regularPath]),
)
